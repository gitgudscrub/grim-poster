import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source = fs.readFileSync('src/grim-poster.js', 'utf8');
const ttl = 86400000;
let stored, fail = false;
const state = {pending:null, uploading:false};
const ctx = {state, Date, RECOVERY_TTL_MS:ttl, PENDING_KEY:'pending', updateStatusButton(){},
  databaseAction:async (_mode, action)=>{if(fail)throw Error('disk');return action({get:()=>stored,delete:()=>{stored=null;},put:c=>{stored=c;}});}};
vm.createContext(ctx);
vm.runInContext(source.slice(source.indexOf('  function recoveryExpired('), source.indexOf('  function injectStyles(')), ctx);
const now=Date.now();
assert.equal(ctx.recoveryExpired({capturedAt:now-ttl+1},now),false);
assert.equal(ctx.recoveryExpired({capturedAt:now-ttl},now),true);
for(const capturedAt of [undefined,NaN,'old',now+1]) assert(ctx.recoveryExpired({capturedAt},now));
stored={capturedAt:now-ttl};await ctx.loadPending();assert.equal(stored,null);assert.equal(state.pending,null);
stored={capturedAt:Date.now()};await ctx.loadPending();assert.equal(state.pending,stored);
state.pending=stored={capturedAt:now-ttl};state.uploading=true;await ctx.expirePending();assert(stored);
state.uploading=false;fail=true;await ctx.expirePending();assert(ctx.recoveryExpired(state.pending));
fail=false;await ctx.expirePending();assert.equal(stored,null);
await ctx.persistPending({capturedAt:now-ttl});assert.equal(stored,null);
console.log('Recovery expiry boundary, restart, in-flight and deletion retry tests passed');
